CREATE TABLE role_permissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT NOT NULL
                      CONSTRAINT fk_role_permission_role REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL
                      CONSTRAINT fk_role_permission_permission REFERENCES permissions (id) ON DELETE CASCADE,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT uk_role_permission_unique UNIQUE (role_id, permission_id)
);

CREATE INDEX idx_role_permissions_role_id       ON role_permissions (role_id);
CREATE INDEX idx_role_permissions_permission_id ON role_permissions (permission_id);
