CREATE TABLE account_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL
                    CONSTRAINT fk_account_role_account REFERENCES accounts (id) ON DELETE CASCADE,
    role_id     BIGINT NOT NULL
                    CONSTRAINT fk_account_role_role REFERENCES roles (id) ON DELETE CASCADE,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by BIGINT,
    expires_at  TIMESTAMP,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    created_by  BIGINT,
    updated_by  BIGINT,
    CONSTRAINT uk_account_role_unique UNIQUE (account_id, role_id)
);

CREATE INDEX idx_account_roles_account_id ON account_roles (account_id);
CREATE INDEX idx_account_roles_role_id    ON account_roles (role_id);
