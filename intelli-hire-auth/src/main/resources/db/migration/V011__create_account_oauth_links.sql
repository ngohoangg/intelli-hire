CREATE TABLE account_oauth_links (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT NOT NULL
                         CONSTRAINT fk_account_oauth_link_account REFERENCES accounts (id) ON DELETE CASCADE,
    provider_id      BIGINT NOT NULL
                         CONSTRAINT fk_account_oauth_link_provider REFERENCES oauth_providers (id),
    provider_user_id VARCHAR(255) NOT NULL,
    provider_email   VARCHAR(255),
    linked_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at     TIMESTAMP,
    CONSTRAINT uk_oauth_provider_user UNIQUE (provider_id, provider_user_id),
    CONSTRAINT uk_account_provider    UNIQUE (account_id, provider_id)
);

CREATE INDEX idx_account_oauth_links_account_id ON account_oauth_links (account_id);
CREATE INDEX idx_account_oauth_links_provider   ON account_oauth_links (provider_id, provider_user_id);
